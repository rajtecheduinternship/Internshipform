/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require('node:assert/strict');
const fs = require('node:fs'); const path = require('node:path');
const { setup, load } = require('./lms-test-harness.cjs');
(async () => {
  const h = await setup();
  try {
    const { pool, lms, root } = h;
    for (const file of ['013_examinations.sql', '014_exam_result_publication.sql', '014_exam_result_publication.sql']) await pool.query(fs.readFileSync(path.join(root, 'migrations', file), 'utf8'));
    const errors = load('lib/learning-errors.ts');
    const originalLog = console.error; const logged = [];
    try {
      console.error = (...values) => logged.push(values);
      const secretError = new Error('PRIVATE ANSWER KEY AND SCORE 33.33');
      secretError.detail = 'question answer_index=1';
      const response = errors.learningErrorResponse(secretError);
      assert.equal(response.status,500);
      assert.equal(JSON.stringify(await response.json()).includes('PRIVATE'),false);
      assert.equal(JSON.stringify(logged).includes('33.33'),false);
      assert.equal(JSON.stringify(logged).includes('answer_index'),false);
    } finally { console.error = originalLog; }

    const mocks = { ...h.mocks, '@/lib/lms': lms, '@/lib/learning-errors': errors };
    mocks['@/lib/exam-validation'] = load('lib/exam-validation.ts', mocks);
    const exams = load('lib/exams.ts', mocks);
    const course = (await pool.query("INSERT INTO courses(title,slug,is_published) VALUES('A','a',true) RETURNING id")).rows[0].id;
    const otherCourse = (await pool.query("INSERT INTO courses(title,slug,is_published) VALUES('B','b',true) RETURNING id")).rows[0].id;
    const mod = (await pool.query("INSERT INTO modules(title,is_published) VALUES('M',true) RETURNING id")).rows[0].id;
    await pool.query('INSERT INTO course_modules(course_id,module_id) VALUES($1,$2)', [course,mod]);
    const ids = [];
    for (let i = 0; i < 3; i++) ids.push((await pool.query("INSERT INTO profiles(full_name,email,phone,role,course_id) VALUES($1,$2,$3,'student',$4) RETURNING id", ['Student ' + i, `result${i}@example.test`, '000000000' + i,course])).rows[0].id);
    const bank = await exams.saveBank(course, mod, [0,1,2].map((i) => ({ prompt: 'Question ' + i, options: ['Right', 'Wrong'], answer_index: 0 })));
    const raw = { course_id: course, module_id: mod, title: 'Exam', duration_minutes: 20, pass_percent: 34, requires_module_completion: false, question_ids: bank.map((q) => q.id) };
    const exam = await exams.saveExam(raw); await exams.publishExam(exam.id, true);
    const args = { examId: exam.id, courseId: course, studentId: ids[0], action: 'start' };
    assert.equal((await exams.studentExams(course,ids[0]))[0].attempt_status,'not_started');
    const started = await exams.attemptExam(args);
    assert.equal((await exams.studentExams(course,ids[0]))[0].attempt_status,'in_progress');
    await assert.rejects(exams.publishExamResults(exam.id,true,started.id), /unfinished/);
    await assert.rejects(exams.adminAnswerReview(exam.id,started.id), /after submission/);
    const stored = (await pool.query('SELECT * FROM exam_attempts WHERE id=$1',[started.id])).rows[0];
    const [q1,q2] = stored.questions;
    const answers = { [q1.id]: q1.answer_index, [q2.id]: 1 - q2.answer_index };
    const submitted = await exams.attemptExam({ ...args, action: 'submit', answers });
    assert.equal(submitted.score_percent,null); assert.equal(submitted.correct_count,null); assert.equal(submitted.passed,null);
    assert.equal(JSON.stringify(submitted).includes('answer_index'),false);
    assert.equal(JSON.stringify(submitted).includes('correct_index'),false);
    const privateCard = (await exams.studentExams(course,ids[0]))[0];
    assert.equal(privateCard.attempt_status,'submitted'); assert.equal(privateCard.score_percent,null); assert.equal(privateCard.passed,null);
    assert.equal((await exams.adminStudentExams(ids[0]))[0].score_percent,33.33);
    const review = await exams.adminAnswerReview(exam.id,started.id);
    assert.equal(review.grade.correct_count,1); assert.equal(review.grade.incorrect_count,1); assert.equal(review.grade.unanswered_count,1);
    assert.equal(review.grade.score_percent,33.33); assert.equal(review.grade.passed,false); assert.equal(review.grade.pass_percent,34);
    assert.equal(review.grade.questions[0].selected_answer,q1.options[q1.answer_index]);
    assert.equal(review.grade.questions[2].selected_index,null); assert.equal(review.grade.questions[2].marks_awarded,0);
    await exams.saveBank(course,mod,[{ prompt: 'Changed later', options: ['New A','New B'], answer_index:1 }],q1.id);
    assert.deepEqual((await exams.adminAnswerReview(exam.id,started.id)).grade,review.grade, 'immutable per-attempt snapshot');
    const wrongExam = await exams.saveExam({ ...raw,title:'Other exam' });
    await assert.rejects(exams.adminAnswerReview(wrongExam.id,started.id), /not found/);
    await assert.rejects(exams.publishExamResults(wrongExam.id,true,started.id), /not found/);
    await assert.rejects(exams.publishExamResults(exam.id,'true',started.id), /Invalid/);
    assert.equal((await exams.publishExamResults(exam.id,true,started.id)).updated,1);
    const released = await exams.attemptExam({ ...args,action:'read' });
    assert.equal(released.score_percent,33.33); assert.equal(released.passed,false); assert(released.result_published_at);
    await exams.publishExamResults(exam.id,true,started.id);
    assert.equal(+(await exams.attemptExam({ ...args,action:'read' })).result_published_at,+released.result_published_at,'repeat release does not change timestamp');
    const before = (await pool.query('SELECT answers,correct_count,score_percent FROM exam_attempts WHERE id=$1',[started.id])).rows[0];
    await exams.publishExamResults(exam.id,false,started.id);
    assert.equal((await exams.attemptExam({ ...args,action:'read' })).score_percent,null);
    assert.deepEqual((await pool.query('SELECT answers,correct_count,score_percent FROM exam_attempts WHERE id=$1',[started.id])).rows[0],before,'withdrawal never erases internal records');
    await exams.publishExamResults(exam.id,true);
    await exams.attemptExam({ ...args,studentId:ids[1] });
    const secondSubmit = await exams.attemptExam({ ...args,studentId:ids[1],action:'submit',answers:{} });
    assert.equal(secondSubmit.score_percent,null,'future submissions are not automatically released');
    assert.equal(await exams.attemptExam({ ...args,studentId:ids[2],action:'read' }),null,'student cannot select someone else\'s attempt');
    await assert.rejects(exams.attemptExam({ ...args,courseId:otherCourse,action:'read' }), /not available/);
    const exp = await exams.attemptExam({ ...args,studentId:ids[2] });
    await pool.query("UPDATE exam_attempts SET deadline_at=clock_timestamp()-interval '1 second' WHERE id=$1",[exp.id]);
    assert.equal((await exams.studentExams(course,ids[2]))[0].attempt_status,'submitted');
    assert.equal((await exams.adminExamResults(exam.id)).find((r)=>r.id===exp.id).score_percent,0);
    await exams.publishExamResults(exam.id,true);
    assert((await exams.adminExamResults(exam.id)).every((r)=>r.result_published_at));
    await exams.publishExam(exam.id,false); await pool.query('UPDATE modules SET is_published=false WHERE id=$1',[mod]);
    assert.equal((await exams.studentExams(course,ids[0]))[0].score_percent,33.33,'released historical result survives hiding exam/mod');
    assert.equal((await exams.attemptExam({ ...args,action:'read' })).score_percent,33.33);
    await assert.rejects(exams.attemptExam(args), /not available/);
    await exams.publishExamResults(exam.id,false,started.id);
    await assert.rejects(exams.attemptExam({ ...args,action:'read' }), /not available/);
    await pool.query('UPDATE courses SET is_published=false WHERE id=$1',[course]);
    assert.equal((await exams.studentExams(course,ids[1])).length,0,'course publication gate remains');
    // Real signed admin guard + request parsing, with synthetic approval access only.
    process.env.SESSION_SECRET='result-guard-test-secret';
    const auth = load('lib/auth.ts',{ '@/lib/db':{ db:{} } });
    const route = load('app/api/admin/exams/[id]/results/[attemptId]/route.ts',{ ...mocks,'@/lib/auth':auth,'@/lib/exams':exams });
    const { NextRequest } = require('next/server');
    const request=(body,cookie,origin='http://localhost')=>new NextRequest('http://localhost/api/test',{ method:'PATCH',headers:{ host:'localhost',origin,...(cookie?{cookie}:{}),'content-type':'application/json' },body:JSON.stringify(body) });
    const ctx={params:Promise.resolve({id:exam.id,attemptId:started.id})};
    assert.equal((await route.PATCH(request({is_published:true}),ctx)).status,401);
    const studentCookie=`${auth.SESSION_COOKIE}=${auth.createSessionToken(ids[0],0)}`;
    assert.equal((await route.PATCH(request({is_published:true},studentCookie),ctx)).status,401);
    const adminCookie=`${auth.ADMIN_COOKIE}=${auth.createAdminToken()}`;
    assert.equal((await route.PATCH(request({is_published:true},adminCookie,'https://evil.test'),ctx)).status,403);
    for (const body of [{is_published:'true'}, {is_published:true,score_percent:100},null,[],{}]) assert.equal((await route.PATCH(request(body,adminCookie),ctx)).status,400);
    assert.equal((await route.PATCH(request({is_published:true},adminCookie),ctx)).status,200);
    const after = (await pool.query('SELECT answers,correct_count,score_percent FROM exam_attempts WHERE id=$1',[started.id])).rows[0]; assert.deepEqual(after,before);
    console.log('PASS private-by-default results; detailed shuffled answer/mark review; snapshot stability; per-student and bulk release/withdrawal; no future auto-release; historical-result visibility; expiry; enrollment/role/CSRF/payload negatives; immutable scores; migration idempotence');
  } finally { await h.cleanup(); }
})().catch((e)=>{ console.error(e); process.exitCode=1; });
